// pacmanTool skips the test when a host tool is missing.
func pacmanTool(t *testing.T, name string) string {
	t.Helper()

	p, err := exec.LookPath(name)
	if err != nil {
		t.Skipf("%s not installed", name)
	}

	return p
}

// TestWriteAcceptedByHostTools checks the written package against the real
// pacman and bsdtar: bsdtar lists it, reads the .MTREE as an mtree archive and
// pacman reads its metadata and file list.
func TestWriteAcceptedByHostTools(t *testing.T) {
	bsdtar := pacmanTool(t, "bsdtar")
	pacman := pacmanTool(t, "pacman")

	dir := t.TempDir()
	s := sampleSpec()

	for _, comp := range []string{CompressionZstd, CompressionXZ, CompressionGzip} {
		pkgPath := filepath.Join(dir, s.FileName(comp))
		if err := s.WriteFile(pkgPath, WriteOptions{Compression: comp, Generator: "tool 1.2"}); err != nil {
			t.Fatal(err)
		}

		list, err := exec.Command(bsdtar, "-tf", pkgPath).CombinedOutput()
		if err != nil {
			t.Fatalf("bsdtar -tf (%s): %v\n%s", comp, err, list)
		}

		if !strings.HasPrefix(string(list), ".PKGINFO\n.BUILDINFO\n.MTREE\n.INSTALL\n.CHANGELOG\n") {
			t.Errorf("bsdtar listing (%s):\n%s", comp, list)
		}

		// The .MTREE parses as an mtree archive and describes the payload.
		mtree := filepath.Join(dir, "mtree-"+comp)

		out, err := exec.Command(bsdtar, "-xOf", pkgPath, ".MTREE").Output()
		if err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(mtree, out, 0o600); err != nil {
			t.Fatal(err)
		}

		mt, err := exec.Command(bsdtar, "-tvf", mtree).CombinedOutput()
		if err != nil {
			t.Fatalf("bsdtar cannot read .MTREE: %v\n%s", err, mt)
		}

		if !strings.Contains(string(mt), "usr/bin/hello") || !strings.Contains(string(mt), "hello with space") {
			t.Errorf("mtree listing:\n%s", mt)
		}

		cmd := exec.Command(pacman, "--noconfirm", "-Qpi", pkgPath)
		cmd.Env = append(os.Environ(), "LC_ALL=C")

		info, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("pacman -Qpi (%s): %v\n%s", comp, err, info)
		}

		for _, want := range []string{
			"Name            : hello", "Version         : 1:2.12-3", "Description     : The classic greeting",
			"Architecture    : x86_64", "Licenses        : GPL-3.0-or-later  MIT", "Groups          : greetings",
			"Provides        : greeter=2", "Depends On      : glibc  sh>=5", "Conflicts With  : hi",
			"Replaces        : hola", "Install Script  : Yes",
		} {
			if !strings.Contains(string(info), want) {
				t.Errorf("pacman -Qpi (%s) misses %q:\n%s", comp, want, info)
			}
		}

		files, err := exec.Command(pacman, "-Qpl", pkgPath).CombinedOutput()
		if err != nil {
			t.Fatalf("pacman -Qpl: %v\n%s", err, files)
		}

		if !strings.Contains(string(files), "hello /usr/bin/hello\n") ||
			!strings.Contains(string(files), "hello /usr/share/doc/hello with space/README\n") {
			t.Errorf("pacman -Qpl (%s):\n%s", comp, files)
		}
	}
}

// TestSyncDBAcceptedByPacman: a database written by WriteDB from a written
// package is read by pacman's sync machinery.
func TestPackageAcceptedByRepoAdd(t *testing.T) {
	repoAdd := pacmanTool(t, "repo-add")

	dir := t.TempDir()
	s := sampleSpec()
	pkgPath := filepath.Join(dir, s.FileName(CompressionZstd))

	if err := s.WriteFile(pkgPath, WriteOptions{}); err != nil {
		t.Fatal(err)
	}

	db := filepath.Join(dir, "test.db.tar.gz")

	if out, err := exec.Command(repoAdd, db, pkgPath).CombinedOutput(); err != nil {
		t.Fatalf("repo-add: %v\n%s", err, out)
	}

	f, err := os.Open(db)
	if err != nil {
		t.Fatal(err)
	}

	defer func() { _ = f.Close() }()

	entries, err := ReadDB(f)
	if err != nil {
		t.Fatal(err)
	}

	if len(entries) != 1 {
		t.Fatalf("entries = %+v", entries)
	}

	e := entries[0]
	if e.Name != "hello" || e.Version != "1:2.12-3" || e.Filename != s.FileName(CompressionZstd) ||
		fmt.Sprint(e.Depends) != "[glibc sh>=5]" || fmt.Sprint(e.Provides) != "[greeter=2]" || e.BuildDate != buildTime {
		t.Errorf("entry %+v", e)
	}

	fi, _ := os.Stat(pkgPath)
	if e.CSize != fi.Size() || len(e.SHA256) != 64 {
		t.Errorf("sizes %d %d, sha %q", e.CSize, fi.Size(), e.SHA256)
	}
}

// TestWriteInstallableByPacman installs the written package into a scratch
// root with the real pacman (inside a user namespace) and has pacman check the
// installed files against the .MTREE.
func TestWriteInstallableByPacman(t *testing.T) {
	pacman := pacmanTool(t, "pacman")
	unshare := pacmanTool(t, "unshare")

	if err := exec.Command(unshare, "-rm", "true").Run(); err != nil {
		t.Skipf("no user namespaces: %v", err)
	}

	base := t.TempDir()
	root := filepath.Join(base, "root")
	conf := filepath.Join(base, "pacman.conf")

	for _, d := range []string{"db", "cache", "gnupg"} {
		if err := os.MkdirAll(filepath.Join(root, d), 0o755); err != nil {
			t.Fatal(err)
		}
	}

	if err := os.WriteFile(conf, []byte("[options]\nSigLevel = Never\nLocalFileSigLevel = Never\nArchitecture = x86_64\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	common := []string{
		"-rm", pacman, "--root", root, "--dbpath", filepath.Join(root, "db"),
		"--cachedir", filepath.Join(root, "cache"), "--gpgdir", filepath.Join(root, "gnupg"), "--config", conf,
	}

	s := sampleSpec()
	pkgPath := filepath.Join(base, s.FileName(CompressionZstd))

	if err := s.WriteFile(pkgPath, WriteOptions{ClampMTime: true}); err != nil {
		t.Fatal(err)
	}

	run := func(args ...string) string {
		t.Helper()

		out, err := exec.Command(unshare, append(slices.Clone(common), args...)...).CombinedOutput()
		if err != nil {
			t.Fatalf("pacman %v: %v\n%s", args, err, out)
		}

		return string(out)
	}

	run("--noconfirm", "--noscriptlet", "-dd", "-U", pkgPath)

	if got, err := os.ReadFile(filepath.Join(root, "usr/bin/hello")); err != nil || string(got) != "#!/bin/sh\necho hi\n" {
		t.Fatalf("installed file: %q, %v", got, err)
	}

	if target, err := os.Readlink(filepath.Join(root, "usr/bin/hi")); err != nil || target != "hello" {
		t.Fatalf("installed link: %q, %v", target, err)
	}

	if out := run("-Qkk", "hello"); !strings.Contains(out, "0 altered files") {
		t.Errorf("pacman -Qkk:\n%s", out)
	}
}
