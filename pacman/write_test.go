func TestScanDirAndWriteFile(t *testing.T) {
	t.Parallel()

	root := t.TempDir()

	must := func(err error) {
		t.Helper()

		if err != nil {
			t.Fatal(err)
		}
	}

	must(os.MkdirAll(filepath.Join(root, "usr/bin"), 0o755))
	must(os.WriteFile(filepath.Join(root, "usr/bin/tool"), []byte("bin"), 0o755))
	must(os.Symlink("tool", filepath.Join(root, "usr/bin/t")))
	must(os.WriteFile(filepath.Join(root, ".PKGINFO"), []byte("stale"), 0o644))
	must(os.WriteFile(filepath.Join(root, ".MTREE"), []byte("stale"), 0o644))

	files, err := ScanDir(root)
	if err != nil {
		t.Fatal(err)
	}

	var paths []string
	for _, f := range files {
		paths = append(paths, f.Path)
	}

	if fmt.Sprint(paths) != "[usr usr/bin usr/bin/t usr/bin/tool]" {
		t.Fatalf("paths %v", paths)
	}

	s := &Spec{Info: PkgInfo{Name: "tool", Version: "1-1", Arch: "any", BuildDate: buildTime}, Files: files}
	out := filepath.Join(t.TempDir(), s.FileName(""))

	must(s.WriteFile(out, WriteOptions{}))

	f, err := os.Open(out)
	must(err)

	defer func() { _ = f.Close() }()

	pkg, err := ReadPackage(f)
	must(err)

	if fmt.Sprint(pkg.Files) != "[usr/ usr/bin/ usr/bin/t usr/bin/tool]" || pkg.Info.InstalledSz != 3 {
		t.Errorf("package %+v %+v", pkg.Files, pkg.Info)
	}

	if filepath.Base(out) != "tool-1-1-any.pkg.tar.zst" {
		t.Errorf("file name %s", out)
	}

	entries, _ := os.ReadDir(filepath.Dir(out))
	if len(entries) != 1 {
		t.Errorf("leftover files: %v", entries)
	}
}

