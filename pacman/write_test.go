func writeSpec(t *testing.T, s *Spec, opts WriteOptions) []byte {
	t.Helper()

	var buf bytes.Buffer
	if err := s.Write(&buf, opts); err != nil {
		t.Fatalf("Write: %v", err)
	}

	return buf.Bytes()
}

func TestWriteRoundTrip(t *testing.T) {
	t.Parallel()

	for _, kind := range []string{"", CompressionZstd, CompressionXZ, CompressionGzip} {
		t.Run(kind, func(t *testing.T) {
			t.Parallel()

			s := sampleSpec()
			raw := writeSpec(t, s, WriteOptions{Compression: kind, Generator: "tool 1.2"})

			pkg, err := ReadPackage(bytes.NewReader(raw))
			if err != nil {
				t.Fatalf("ReadPackage: %v", err)
			}

			want := kind
			if want == "" {
				want = CompressionZstd
			}

			if pkg.Compression != want {
				t.Errorf("compression %q, want %q", pkg.Compression, want)
			}

			in := s.Info
			in.Base = in.Name
			in.InstalledSz = int64(len("#!/bin/sh\necho hi\n") + len("greeting=hi\n") + len("read me") + 1)

			if got := pkg.Info; fmt.Sprint(*got) != fmt.Sprint(in) {
				t.Errorf("info = %+v\nwant   %+v", *got, in)
			}

			wantFiles := []string{
				"etc/", "etc/hello.conf", "usr/", "usr/bin/", "usr/bin/hello", "usr/bin/hi", "usr/bin/suid",
				"usr/share/", "usr/share/doc/", "usr/share/doc/hello with space/",
				"usr/share/doc/hello with space/README", "var/", "var/lib/", "var/lib/hello/",
			}
			if fmt.Sprint(pkg.Files) != fmt.Sprint(wantFiles) {
				t.Errorf("files = %q\nwant    %q", pkg.Files, wantFiles)
			}
		})
	}
}

// members reads the tar of a zstd package: names in order and bodies.
func members(t *testing.T, raw []byte) ([]*tar.Header, map[string][]byte) {
	t.Helper()

	dec, _, closeDec, err := openCompressed(bytes.NewReader(raw))
	if err != nil {
		t.Fatal(err)
	}

	defer closeDec()

	tr := tar.NewReader(dec)
	bodies := map[string][]byte{}

	var hdrs []*tar.Header

	for {
		h, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}

		if err != nil {
			t.Fatal(err)
		}

		b, _ := io.ReadAll(tr)
		bodies[h.Name] = b

		hdrs = append(hdrs, h)
	}

	return hdrs, bodies
}

func TestWriteLayoutAndMetadata(t *testing.T) {
	t.Parallel()

	raw := writeSpec(t, sampleSpec(), WriteOptions{Generator: "tool 1.2"})
	hdrs, bodies := members(t, raw)

	var names []string
	for _, h := range hdrs {
		names = append(names, h.Name)
	}

	head := []string{".PKGINFO", ".BUILDINFO", ".MTREE", ".INSTALL", ".CHANGELOG", "etc/", "etc/hello.conf"}
	if fmt.Sprint(names[:len(head)]) != fmt.Sprint(head) {
		t.Fatalf("order %q", names)
	}

	for _, h := range hdrs {
		if h.Uid != 0 || h.Gid != 0 || h.Uname != "root" || h.Gname != "root" {
			t.Errorf("%s owner %d:%d %s:%s", h.Name, h.Uid, h.Gid, h.Uname, h.Gname)
		}
	}

	if !strings.HasPrefix(string(bodies[".PKGINFO"]), "# Generated by tool 1.2\npkgname = hello\npkgbase = hello\nxdata = pkgtype=pkg\n") {
		t.Errorf("PKGINFO:\n%s", bodies[".PKGINFO"])
	}

	bi, err := ParseBuildInfo(bytes.NewReader(bodies[".BUILDINFO"]))
	if err != nil {
		t.Fatal(err)
	}

	if bi.Format != 2 || bi.PkgName != "hello" || bi.PkgBase != "hello" || bi.PkgVer != "1:2.12-3" ||
		bi.PkgArch != "x86_64" || bi.BuildDate != buildTime || bi.Packager != "Jane <jane@example.org>" ||
		bi.BuildTool != "tool" || fmt.Sprint(bi.Options) != "[strip !debug]" || bi.StartDir != "/src" {
		t.Errorf("BUILDINFO %+v", bi)
	}

	install := string(bodies[".INSTALL"])
	for _, w := range []string{
		"helper() { :; }\n", "\npost_install() {\necho installed\n}", "\npost_upgrade() {\necho installed\n}",
		"\npre_remove() {\necho removing\n}",
	} {
		if !strings.Contains(install, w) {
			t.Errorf(".INSTALL misses %q:\n%s", w, install)
		}
	}

	for _, absent := range []string{"pre_install()", "pre_upgrade()", "post_remove()"} {
		if strings.Contains(install, absent) {
			t.Errorf(".INSTALL has %s", absent)
		}
	}

	if string(bodies[".CHANGELOG"]) != "1.0: first\n" {
		t.Errorf("CHANGELOG %q", bodies[".CHANGELOG"])
	}

	// Metadata files carry the build date.
	for _, h := range hdrs[:5] {
		if h.ModTime.Unix() != buildTime {
			t.Errorf("%s mtime %d", h.Name, h.ModTime.Unix())
		}
	}

	checkMtree(t, bodies[".MTREE"], hdrs, bodies)

	mt := mtreeLines(t, bodies[".MTREE"])
	if !strings.Contains(mt["./usr/bin/suid"], " mode=4755 ") {
		t.Errorf("suid line %s", mt["./usr/bin/suid"])
	}

	if !strings.Contains(mt[`./usr/share/doc/hello\040with\040space`], "type=dir") {
		t.Errorf("space in a path is not escaped: %v", mt)
	}
}

func mtreeLines(t *testing.T, gz []byte) map[string]string {
	t.Helper()

	zr, err := gzip.NewReader(bytes.NewReader(gz))
	if err != nil {
		t.Fatal(err)
	}

	text, _ := io.ReadAll(zr)
	m := map[string]string{}

	for l := range strings.SplitSeq(strings.TrimSuffix(string(text), "\n"), "\n") {
		name, _, _ := strings.Cut(l, " ")
		m[name] = l
	}

	return m
}

func checkMtree(t *testing.T, gz []byte, hdrs []*tar.Header, bodies map[string][]byte) {
	t.Helper()

	zr, err := gzip.NewReader(bytes.NewReader(gz))
	if err != nil {
		t.Fatalf("MTREE is not gzip: %v", err)
	}

	text, err := io.ReadAll(zr)
	if err != nil {
		t.Fatal(err)
	}

	lines := strings.Split(strings.TrimSuffix(string(text), "\n"), "\n")
	if lines[0] != "#mtree" || lines[1] != "/set type=file uid=0 gid=0 mode=644" {
		t.Fatalf("MTREE head %q", lines[:2])
	}

	byName := map[string]string{}

	for _, l := range lines[2:] {
		name, _, _ := strings.Cut(l, " ")
		byName[name] = l
	}

	for _, h := range hdrs {
		if h.Name == ".MTREE" {
			if _, ok := byName["./.MTREE"]; ok {
				t.Error("MTREE lists itself")
			}

			continue
		}

		name := "./" + mtreeEscape(strings.TrimSuffix(h.Name, "/"))

		line, ok := byName[name]
		if !ok {
			t.Errorf("MTREE misses %s", name)

			continue
		}

		if !strings.Contains(line, fmt.Sprintf(" time=%d.0", h.ModTime.Unix())) {
			t.Errorf("%s: wrong time: %s", name, line)
		}

		switch h.Typeflag {
		case tar.TypeDir:
			if !strings.Contains(line, "type=dir") || !strings.Contains(line, " mode="+mtreeMode(modeOf(h))) {
				t.Errorf("dir line %s", line)
			}
		case tar.TypeSymlink:
			if !strings.Contains(line, "type=link link="+h.Linkname) {
				t.Errorf("link line %s", line)
			}
		default:
			sum := sha256.Sum256(bodies[h.Name])
			if !strings.Contains(line, fmt.Sprintf(" size=%d sha256digest=%s", h.Size, hex.EncodeToString(sum[:]))) {
				t.Errorf("file line %s", line)
			}
		}
	}

	if strings.Contains(byName["./.PKGINFO"], "mode=") {
		t.Errorf(".PKGINFO line has a mode: %s", byName["./.PKGINFO"])
	}

}

func TestWriteDeterministic(t *testing.T) {
	t.Parallel()

	mk := func(skew time.Duration) []byte {
		s := sampleSpec()
		for i := range s.Files {
			if s.Files[i].Mode&fs.ModeDir == 0 {
				s.Files[i].ModTime = time.Unix(buildTime+1000, 0).Add(skew)
			}
		}

		// Reverse the order: the archive must not depend on it.
		for i, j := 0, len(s.Files)-1; i < j; i, j = i+1, j-1 {
			s.Files[i], s.Files[j] = s.Files[j], s.Files[i]
		}

		return writeSpec(t, s, WriteOptions{ClampMTime: true})
	}

	if !bytes.Equal(mk(0), mk(5*time.Hour)) {
		t.Error("equal input produced different bytes")
	}

	hdrs, _ := members(t, mk(0))
	for _, h := range hdrs {
		if h.ModTime.Unix() > buildTime {
			t.Errorf("%s mtime %d after the build date", h.Name, h.ModTime.Unix())
		}
	}
}

func TestWriteOpenReader(t *testing.T) {
	t.Parallel()

	body := bytes.Repeat([]byte("0123456789"), 10000)
	open := func() (io.ReadCloser, error) { return io.NopCloser(bytes.NewReader(body)), nil }

	s := &Spec{
		Info:  PkgInfo{Name: "big", Version: "1-1", Arch: "any"},
		Files: []File{{Path: "opt/big", Mode: 0o644, Open: open, Size: int64(len(body))}},
	}

	raw := writeSpec(t, s, WriteOptions{})
	hdrs, bodies := members(t, raw)

	if !bytes.Equal(bodies["opt/big"], body) {
		t.Fatal("content differs")
	}

	checkMtree(t, bodies[".MTREE"], hdrs, bodies)

	for _, size := range []int64{int64(len(body)) - 1, int64(len(body)) + 1} {
		s.Files[0].Size = size

		if err := s.Write(io.Discard, WriteOptions{}); !errors.Is(err, ErrInvalidFile) {
			t.Errorf("size %d: err = %v", size, err)
		}
	}

	// Content that changes between the checksum pass and the write pass.
	n := 0
	s.Files[0].Size = int64(len(body))
	s.Files[0].Open = func() (io.ReadCloser, error) {
		n++

		b := bytes.Clone(body)
		if n > 1 {
			b[0] = 'X'
		}

		return io.NopCloser(bytes.NewReader(b)), nil
	}

	if err := s.Write(io.Discard, WriteOptions{}); !errors.Is(err, ErrInvalidFile) {
		t.Errorf("changing content: err = %v", err)
	}
}

