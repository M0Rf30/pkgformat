package pacman

import (
	"bufio"
	"fmt"
	"io"
	"strconv"
	"strings"
	"unicode/utf8"
)

// checkLine reports a value that cannot be written on one line of a metadata
// file: a newline or carriage return would start a new key, a NUL is never text.
func checkLine(key, value string) error {
	if strings.ContainsAny(value, "\n\r\x00") {
		return fmt.Errorf("%w: %s contains a line break or NUL", ErrInvalidField, key)
	}

	if !utf8.ValidString(value) {
		return fmt.Errorf("%w: %s is not UTF-8", ErrInvalidField, key)
	}

	if len(value) > MaxValueLen {
		return fmt.Errorf("%w: %s is too long", ErrInvalidField, key)
	}

	return nil
}

func checkList(key string, values []string) error {
	if len(values) > MaxListEntries {
		return fmt.Errorf("%w: too many %s entries", ErrInvalidField, key)
	}

	for _, v := range values {
		if err := checkLine(key, v); err != nil {
			return err
		}
	}

	return nil
}

// Validate checks that the PkgInfo can be written and read back: a valid name,
// version and architecture, a valid base name (the name when empty), values
// without line breaks and within the field limits. It fills an empty Base with
// the name, as ParsePkgInfo does.
func (p *PkgInfo) Validate() error {
	if err := p.validate(); err != nil {
		return err
	}

	if p.BuildDate < 0 || p.InstalledSz < 0 {
		return fmt.Errorf("%w: negative number", ErrInvalidField)
	}

	for _, f := range []struct{ key, val string }{
		{"pkgname", p.Name}, {"pkgbase", p.Base}, {"pkgver", p.Version}, {"pkgdesc", p.Description},
		{"url", p.URL}, {"packager", p.Packager}, {"arch", p.Arch},
	} {
		if err := checkLine(f.key, f.val); err != nil {
			return err
		}
	}

	for _, l := range []struct {
		key  string
		list []string
	}{
		{"license", p.Licenses}, {"group", p.Groups}, {"replaces", p.Replaces}, {"conflict", p.Conflicts},
		{"provides", p.Provides}, {"backup", p.Backup}, {"depend", p.Depends}, {"optdepend", p.OptDepends},
		{"makedepend", p.MakeDepends}, {"checkdepend", p.CheckDepends}, {"xdata", p.XData},
	} {
		if err := checkList(l.key, l.list); err != nil {
			return err
		}
	}

	return nil
}

// Render returns the text of the .PKGINFO in the order makepkg writes it,
// after Validate. generator, when not empty, names the tool in the leading
// "# Generated by" comment.
func (p *PkgInfo) Render(generator string) ([]byte, error) {
	if err := p.Validate(); err != nil {
		return nil, err
	}

	if err := checkLine("generator", generator); err != nil {
		return nil, err
	}

	var b strings.Builder

	if generator != "" {
		b.WriteString("# Generated by " + generator + "\n")
	}

	kv := func(key, value string) { b.WriteString(key + " = " + value + "\n") }

	list := func(key string, values []string) {
		for _, v := range values {
			kv(key, v)
		}
	}

	kv("pkgname", p.Name)
	kv("pkgbase", p.Base)
	list("xdata", p.XData)
	kv("pkgver", p.Version)
	kv("pkgdesc", p.Description)
	kv("url", p.URL)
	kv("builddate", strconv.FormatInt(p.BuildDate, 10))

	if p.Packager != "" {
		kv("packager", p.Packager)
	}

	kv("size", strconv.FormatInt(p.InstalledSz, 10))
	kv("arch", p.Arch)
	list("license", p.Licenses)
	list("replaces", p.Replaces)
	list("group", p.Groups)
	list("conflict", p.Conflicts)
	list("provides", p.Provides)
	list("backup", p.Backup)
	list("depend", p.Depends)
	list("optdepend", p.OptDepends)
	list("makedepend", p.MakeDepends)
	list("checkdepend", p.CheckDepends)

	return []byte(b.String()), nil
}

// MaxBuildInfoBytes bounds a .BUILDINFO.
const MaxBuildInfoBytes = 1 << 20

// BuildInfo is the .BUILDINFO of a package: how and where it was built.
type BuildInfo struct {
	// Format is the .BUILDINFO format; zero means 2, the one makepkg writes.
	Format         int
	PkgName        string
	PkgBase        string
	PkgVer         string // [epoch:]pkgver-pkgrel
	PkgArch        string
	PkgbuildSHA256 string // hex SHA-256 of the build recipe
	Packager       string
	BuildDate      int64
	BuildDir       string
	StartDir       string
	BuildTool      string
	BuildToolVer   string
	BuildEnv       []string
	Options        []string
	// Installed lists the packages present in the build environment, each
	// "name-version-arch".
	Installed []string
}

// ParseBuildInfo parses the text of a .BUILDINFO. Unknown keys are ignored. A
// malformed number or a value over the limits is an error.
func ParseBuildInfo(r io.Reader) (*BuildInfo, error) {
	data, err := io.ReadAll(io.LimitReader(r, MaxBuildInfoBytes+1))
	if err != nil {
		return nil, fmt.Errorf("pacman: reading .BUILDINFO: %w", err)
	}

	if len(data) > MaxBuildInfoBytes {
		return nil, fmt.Errorf("%w: .BUILDINFO too large", ErrInvalidField)
	}

	if !utf8.Valid(data) {
		return nil, fmt.Errorf("%w: .BUILDINFO is not UTF-8", ErrInvalidField)
	}

	bi := &BuildInfo{}
	sc := bufio.NewScanner(strings.NewReader(string(data)))
	sc.Buffer(make([]byte, 0, 64<<10), MaxBuildInfoBytes+1)

	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || line[0] == '#' {
			continue
		}

		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}

		if err := bi.set(strings.TrimSpace(key), strings.TrimSpace(value)); err != nil {
			return nil, err
		}
	}

	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("pacman: scanning .BUILDINFO: %w", err)
	}

	return bi, nil
}

func (b *BuildInfo) set(key, value string) error {
	if len(value) > MaxValueLen {
		return fmt.Errorf("%w: %s is too long", ErrInvalidField, key)
	}

	switch key {
	case "format":
		n, err := strconv.Atoi(value)
		if err != nil || n < 0 {
			return fmt.Errorf("%w: format %q", ErrInvalidField, value)
		}

		b.Format = n
	case "pkgname":
		b.PkgName = value
	case "pkgbase":
		b.PkgBase = value
	case "pkgver":
		b.PkgVer = value
	case "pkgarch":
		b.PkgArch = value
	case "pkgbuild_sha256sum":
		b.PkgbuildSHA256 = value
	case "packager":
		b.Packager = value
	case "builddate":
		return parseNonNegative(key, value, &b.BuildDate)
	case "builddir":
		b.BuildDir = value
	case "startdir":
		b.StartDir = value
	case "buildtool":
		b.BuildTool = value
	case "buildtoolver":
		b.BuildToolVer = value
	case "buildenv":
		return appendBounded(&b.BuildEnv, key, value)
	case "options":
		return appendBounded(&b.Options, key, value)
	case "installed":
		return appendBounded(&b.Installed, key, value)
	}

	return nil
}

// Render returns the text of the .BUILDINFO in the order makepkg writes it.
// Empty optional values are left out.
func (b *BuildInfo) Render() ([]byte, error) {
	for _, f := range []struct{ key, val string }{
		{"pkgname", b.PkgName}, {"pkgbase", b.PkgBase}, {"pkgver", b.PkgVer}, {"pkgarch", b.PkgArch},
		{"pkgbuild_sha256sum", b.PkgbuildSHA256}, {"packager", b.Packager}, {"builddir", b.BuildDir},
		{"startdir", b.StartDir}, {"buildtool", b.BuildTool}, {"buildtoolver", b.BuildToolVer},
	} {
		if err := checkLine(f.key, f.val); err != nil {
			return nil, err
		}
	}

	for _, l := range []struct {
		key  string
		list []string
	}{{"buildenv", b.BuildEnv}, {"options", b.Options}, {"installed", b.Installed}} {
		if err := checkList(l.key, l.list); err != nil {
			return nil, err
		}
	}

	if b.BuildDate < 0 || b.Format < 0 {
		return nil, fmt.Errorf("%w: negative number", ErrInvalidField)
	}

	var out strings.Builder

	kv := func(key, value string) {
		if value != "" {
			out.WriteString(key + " = " + value + "\n")
		}
	}

	format := b.Format
	if format == 0 {
		format = 2
	}

	kv("format", strconv.Itoa(format))
	kv("pkgname", b.PkgName)
	kv("pkgbase", b.PkgBase)
	kv("pkgver", b.PkgVer)
	kv("pkgarch", b.PkgArch)
	kv("pkgbuild_sha256sum", b.PkgbuildSHA256)
	kv("packager", b.Packager)
	kv("builddate", strconv.FormatInt(b.BuildDate, 10))
	kv("builddir", b.BuildDir)
	kv("startdir", b.StartDir)
	kv("buildtool", b.BuildTool)
	kv("buildtoolver", b.BuildToolVer)

	for _, l := range []struct {
		key  string
		list []string
	}{{"buildenv", b.BuildEnv}, {"options", b.Options}, {"installed", b.Installed}} {
		for _, v := range l.list {
			kv(l.key, v)
		}
	}

	return []byte(out.String()), nil
}
