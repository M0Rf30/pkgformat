// ErrInvalidSpec is wrapped by every error [WritePackage] returns for a
// [Spec] it refuses.
var ErrInvalidSpec = errors.New("apk: invalid package spec")

func badSpec(format string, args ...any) error {
	return fmt.Errorf("%w: %s", ErrInvalidSpec, fmt.Sprintf(format, args...))
}

// Info is the metadata of a package: what goes into its .PKGINFO. Name,
// Version and Arch are required; the zero value of every other field leaves
// the line out.
type Info struct {
	// Name is the package name (pkgname), Version the complete version
	// including the release (pkgver), for example "1.2.3-r0". Alpine versions
	// have no epoch. Arch is the apk architecture such as x86_64 or noarch.
	Name, Version, Arch string
	// Description (pkgdesc), URL, License (one SPDX expression or a list
	// separated by spaces, as abuild writes it), Origin (the package the
	// build produced it from; the Name when empty), Maintainer, Packager and
	// Commit are the free text lines.
	Description, URL, License, Origin, Maintainer, Packager, Commit string
	// BuildDate is the builddate; the line is left out when it is zero.
	BuildDate time.Time
	// InstalledSize is the size line, the bytes the package takes installed.
	// Zero selects the sum of the sizes of the regular files.
	InstalledSize int64
	// Depends, Provides and Replaces get one depend, provides or replaces
	// line per entry. InstallIf is one install_if line.
	Depends, Provides, Replaces, InstallIf []string
	// ProviderPriority is the provider_priority line; zero leaves it out.
	ProviderPriority int
	// Generator, when set, is written as the first line, a comment:
	// "# Generated by <Generator>".
	Generator string
}

// Scripts are the install scripts of a package. Each is the complete file,
// shebang included, and is stored executable in the control segment under the
// name apk runs it by; an empty script is left out. A script of an install
// hook that also runs on upgrade is set in both fields (PreInstall and
// PreUpgrade), as abuild's single pre-install script would not run on upgrade.
type Scripts struct {
	PreInstall, PostInstall     string
	PreUpgrade, PostUpgrade     string
	PreDeinstall, PostDeinstall string
	// Trigger is the .trigger script.
	Trigger string
}

// scriptNames lists the control entries of Scripts in the order they are
// written.
func (s *Scripts) entries() []struct{ name, body string } {
	return []struct{ name, body string }{
		{".pre-install", s.PreInstall},
		{".post-install", s.PostInstall},
		{".pre-upgrade", s.PreUpgrade},
		{".post-upgrade", s.PostUpgrade},
		{".pre-deinstall", s.PreDeinstall},
		{".post-deinstall", s.PostDeinstall},
		{".trigger", s.Trigger},
	}
}

// File is one entry of the data segment. The kind comes from Mode: a
// directory, a symbolic link, a named pipe or a regular file; any other kind
// (devices, sockets) is refused.
type File struct {
	// Name is the install path: slash separated, relative, without "." or
	// ".." elements. A directory's trailing slash is added when missing.
	Name string
	// Mode holds the type and the permission bits, setuid, setgid and sticky
	// included.
	Mode fs.FileMode
	// Size is the length of a regular file's content.
	Size int64
	// ModTime is the modification time, truncated to the second; the zero time
	// is the epoch.
	ModTime time.Time
	// UID, GID, Uname and Gname are the owner.
	UID, GID     int
	Uname, Gname string
	// LinkTarget is the target of a symbolic link.
	LinkTarget string
	// Open returns the content of a regular file. It is called twice (one pass
	// to record the checksum, one to write) and must return Size bytes both
	// times. Nil is an empty file.
	Open func() (io.ReadCloser, error)
}

// MemFile returns a regular file with the given content, owned by root and
// stamped with the epoch. mode holds the permission bits and may add setuid,
// setgid or sticky.
func MemFile(name string, mode fs.FileMode, data []byte) File {
	return File{
		Name: name, Mode: mode &^ fs.ModeType, Size: int64(len(data)), Uname: "root", Gname: "root",
		Open: func() (io.ReadCloser, error) { return io.NopCloser(bytes.NewReader(data)), nil },
	}
}

// FilesFromDir lists the tree under dir for [Spec.Files]: every entry below
// dir in lexical order, with names relative to dir, links not followed, the
// owner root:root and the modification time the epoch, so the package does not
// depend on who built it or when. The permission bits are kept.
func FilesFromDir(dir string) ([]File, error) {
	dir = filepath.Clean(dir)

	var files []File

	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if p == dir {
			return nil
		}

		info, err := d.Info()
		if err != nil {
			return err
		}

		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}

		f := File{Name: filepath.ToSlash(rel), Mode: info.Mode(), Uname: "root", Gname: "root"}

		switch {
		case info.Mode()&fs.ModeSymlink != 0:
			if f.LinkTarget, err = os.Readlink(p); err != nil {
				return err
			}
		case info.Mode().IsRegular():
			f.Size = info.Size()
			f.Open = func() (io.ReadCloser, error) { return os.Open(p) }
		case !info.IsDir() && info.Mode()&fs.ModeNamedPipe == 0:
			return badSpec("%s: unsupported file type %s", short(f.Name), info.Mode().Type())
		}

		files = append(files, f)

		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("apk: %w", err)
	}

	return files, nil
}

// Spec is everything a package consists of.
type Spec struct {
	Info    Info
	Scripts Scripts
	Files   []File
}

// WriteOptions configures [WritePackage].
type WriteOptions struct {
	// Signer, when set, puts a signature segment of the control segment in
	// front of the package.
	Signer *Signer
	// TempDir is where the compressed data segment is spooled until its hash
	// is known (the control segment, which comes first in the file, records
	// it). Empty selects os.TempDir.
	TempDir string
}

// control entry names that the data segment must not use: apk would read them
// as control files.
func controlName(name string) bool {
	for _, p := range [...]string{pkginfoName, sigPrefix, ".pre-", ".post-", ".trigger"} {
		if strings.HasPrefix(name, p) {
			return true
		}
	}

	return false
}

// WritePackage writes the .apk described by spec to w: the optional signature
// segment, the control segment (.PKGINFO and the install scripts) and the data
// segment, three gzip members as abuild writes them. Each regular file of the
// data segment carries its SHA-1 in a PAX record (APK-TOOLS.checksum.SHA1) and
// the .PKGINFO records the SHA-256 of the data segment (datahash).
//
// The result is deterministic for a given spec. It returns the package as an
// index entry: its checksum, size and datahash, ready for [BuildIndex].
// Errors for a spec it refuses wrap [ErrInvalidSpec].
func WritePackage(w io.Writer, spec *Spec, opts WriteOptions) (*Package, error) {
	files, err := normalizeFiles(spec.Files)
	if err != nil {
		return nil, err
	}

	info := spec.Info
	if info.InstalledSize < 0 {
		return nil, badSpec("negative size")
	}

	if info.InstalledSize == 0 {
		for i := range files {
			if files[i].Mode.IsRegular() {
				info.InstalledSize += files[i].Size
			}
		}
	}

	if info.Origin == "" {
		info.Origin = info.Name
	}

	pkg, err := infoPackage(&info)
	if err != nil {
		return nil, err
	}

	spool, err := os.CreateTemp(opts.TempDir, "apk-data-*.tar.gz")
	if err != nil {
		return nil, fmt.Errorf("apk: spooling the data segment: %w", err)
	}

	defer func() {
		_ = spool.Close()
		_ = os.Remove(spool.Name())
	}()

	dataHash, err := writeData(spool, files)
	if err != nil {
		return nil, err
	}

	pkg.DataHash = dataHash

	control, err := controlSegment(&info, pkg.DataHash, &spec.Scripts)
	if err != nil {
		return nil, err
	}

	sum := sha1.Sum(control) //nolint:gosec // see the import
	pkg.Checksum = checksumPrefix + base64.StdEncoding.EncodeToString(sum[:])

	cw := &countWriter{w: w}

	if opts.Signer != nil {
		member, err := signatureMember(opts.Signer, control, packageGzip)
		if err != nil {
			return nil, fmt.Errorf("apk: signing the control segment: %w", err)
		}

		if _, err := cw.Write(member); err != nil {
			return nil, err
		}

		pkg.Signed = true
	}

	if _, err := cw.Write(control); err != nil {
		return nil, err
	}

	if _, err := spool.Seek(0, io.SeekStart); err != nil {
		return nil, fmt.Errorf("apk: rewinding the data segment: %w", err)
	}

	if _, err := io.Copy(cw, spool); err != nil {
		return nil, err
	}

	pkg.Size = cw.n

	return pkg, nil
}

// countWriter counts the bytes written through it.
type countWriter struct {
	w io.Writer
	n int64
}

func (c *countWriter) Write(p []byte) (int, error) {
	n, err := c.w.Write(p)
	c.n += int64(n)

	return n, err
}

// infoPackage validates info by building the index entry it would give.
func infoPackage(info *Info) (*Package, error) {
	pkg := &Package{
		Name: info.Name, Version: info.Version, Arch: info.Arch,
		Description: info.Description, URL: info.URL, License: info.License, Origin: info.Origin,
		Maintainer: info.Maintainer, Packager: info.Packager, Commit: info.Commit,
		InstalledSize: info.InstalledSize,
		Depends:       info.Depends, Provides: info.Provides, Replaces: info.Replaces, InstallIf: info.InstallIf,
		ProviderPriority: info.ProviderPriority,
	}

	if !info.BuildDate.IsZero() {
		pkg.BuildTime = info.BuildDate.Unix()
	}

	if err := pkg.validateFields(); err != nil {
		return nil, badSpec("%v", err)
	}

	if info.Generator != "" && (len(info.Generator) > maxTokenLen || !cleanText(info.Generator)) {
		return nil, badSpec("generator is longer than %d bytes or has control characters", maxTokenLen)
	}

	return pkg, nil
}

// normalizeFiles checks the names and kinds of files and returns them with
// directory names ending in a slash.
func normalizeFiles(in []File) ([]File, error) {
	files := make([]File, len(in))
	seen := make(map[string]struct{}, len(in))

	for i, f := range in {
		name := strings.TrimSuffix(f.Name, "/")

		if !safeEntryName(name) || path.Clean(name) != name || name == "." {
			return nil, badSpec("file name %q is not a clean relative path", short(f.Name))
		}

		if controlName(name) {
			return nil, badSpec("file name %q is reserved for the control segment", short(f.Name))
		}

		if _, dup := seen[name]; dup {
			return nil, badSpec("file %q appears twice", short(f.Name))
		}

		seen[name] = struct{}{}

		switch {
		case f.Mode.IsDir():
			name += "/"
		case f.Mode&fs.ModeSymlink != 0:
			if f.LinkTarget == "" || strings.IndexByte(f.LinkTarget, 0) >= 0 {
				return nil, badSpec("symbolic link %q has no valid target", short(f.Name))
			}
		case f.Mode.IsRegular():
			if f.Size < 0 {
				return nil, badSpec("file %q has a negative size", short(f.Name))
			}
		case f.Mode&fs.ModeNamedPipe != 0:
		default:
			return nil, badSpec("file %q has an unsupported type %s", short(f.Name), f.Mode.Type())
		}

		f.Name = name
		files[i] = f
	}

	return files, requireParents(files)
}

// requireParents checks that every file's parent directory is an entry of the
// package: apk refuses to extract a file into a directory the package does not
// carry.
func requireParents(files []File) error {
	dirs := make(map[string]struct{}, len(files))

	for i := range files {
		if files[i].Mode.IsDir() {
			dirs[strings.TrimSuffix(files[i].Name, "/")] = struct{}{}
		}
	}

	for i := range files {
		parent := path.Dir(strings.TrimSuffix(files[i].Name, "/"))
		if parent == "." {
			continue
		}

		if _, ok := dirs[parent]; !ok {
			return badSpec("the directory %q of %q is not in the package", short(parent), short(files[i].Name))
		}
	}

	return nil
}

// tarMode returns the tar mode bits of m: permissions, setuid, setgid and
// sticky.
func tarMode(m fs.FileMode) int64 {
	mode := int64(m.Perm())

	if m&fs.ModeSetuid != 0 {
		mode |= 0o4000
	}

	if m&fs.ModeSetgid != 0 {
		mode |= 0o2000
	}

	if m&fs.ModeSticky != 0 {
		mode |= 0o1000
	}

	return mode
}

// header returns the tar header of f.
func (f *File) header() *tar.Header {
	hdr := &tar.Header{
		Name:    f.Name,
		Mode:    tarMode(f.Mode),
		Uid:     f.UID,
		Gid:     f.GID,
		Uname:   f.Uname,
		Gname:   f.Gname,
		ModTime: time.Unix(0, 0),
	}

	if !f.ModTime.IsZero() {
		hdr.ModTime = time.Unix(f.ModTime.Unix(), 0)
	}

	switch {
	case f.Mode.IsDir():
		hdr.Typeflag = tar.TypeDir
	case f.Mode&fs.ModeSymlink != 0:
		hdr.Typeflag = tar.TypeSymlink
		hdr.Linkname = f.LinkTarget
	case f.Mode&fs.ModeNamedPipe != 0:
		hdr.Typeflag = tar.TypeFifo
	default:
		hdr.Typeflag = tar.TypeReg
		hdr.Size = f.Size
	}

	return hdr
}

// writeData writes the data segment (one gzip member holding the files' tar,
// ended with the end-of-archive blocks) to out and returns the hex SHA-256 of
// it.
func writeData(out io.Writer, files []File) (string, error) {
	h := sha256.New()

	gw, err := gzip.NewWriterLevel(io.MultiWriter(out, h), gzip.DefaultCompression)
	if err != nil {
		return "", err
	}

	gw.OS = gzipOSUnix
	tw := tar.NewWriter(gw)

	for i := range files {
		if err := writeEntry(tw, &files[i]); err != nil {
			return "", err
		}
	}

	if err := tw.Close(); err != nil {
		return "", err
	}

	if err := gw.Close(); err != nil {
		return "", err
	}

	return hex.EncodeToString(h.Sum(nil)), nil
}

// writeEntry writes one file: a regular file twice read, once for the SHA-1
// record of its header and once for its content.
func writeEntry(tw *tar.Writer, f *File) error {
	hdr := f.header()

	if hdr.Typeflag != tar.TypeReg {
		if err := tw.WriteHeader(hdr); err != nil {
			return fmt.Errorf("apk: %s: %w", short(f.Name), err)
		}

		return nil
	}

	sum, err := fileChecksum(f)
	if err != nil {
		return err
	}

	hdr.PAXRecords = map[string]string{paxChecksum: sum}

	if err := tw.WriteHeader(hdr); err != nil {
		return fmt.Errorf("apk: %s: %w", short(f.Name), err)
	}

	if f.Size == 0 {
		return nil
	}

	rc, err := f.Open()
	if err != nil {
		return fmt.Errorf("apk: %s: %w", short(f.Name), err)
	}

	defer func() { _ = rc.Close() }()

	if err := copyExactly(tw, rc, f); err != nil {
		return err
	}

	return nil
}

// paxChecksum is the PAX record that holds a file's SHA-1.
const paxChecksum = "APK-TOOLS.checksum.SHA1"

// fileChecksum returns the hex SHA-1 of a regular file's content and checks
// that it is Size bytes long.
func fileChecksum(f *File) (string, error) {
	h := sha1.New() //nolint:gosec // see the import

	if f.Size > 0 {
		rc, err := f.Open()
		if err != nil {
			return "", fmt.Errorf("apk: %s: %w", short(f.Name), err)
		}

		defer func() { _ = rc.Close() }()

		if err := copyExactly(h, rc, f); err != nil {
			return "", err
		}
	}

	return hex.EncodeToString(h.Sum(nil)), nil
}

// copyExactly copies the Size bytes of f's content from r to w and fails when
// r holds fewer or more.
func copyExactly(w io.Writer, r io.Reader, f *File) error {
	n, err := io.Copy(w, io.LimitReader(r, f.Size))
	if err != nil {
		return fmt.Errorf("apk: %s: %w", short(f.Name), err)
	}

	if n != f.Size {
		return badSpec("file %q is shorter than its size %d", short(f.Name), f.Size)
	}

	var extra [1]byte
	if m, _ := r.Read(extra[:]); m > 0 {
		return badSpec("file %q is longer than its size %d", short(f.Name), f.Size)
	}

	return nil
}

// controlSegment returns the control member: the .PKGINFO and the scripts,
// one gzip member whose tar has no end-of-archive blocks, so that apk reads on
// into the data member.
func controlSegment(info *Info, dataHash string, s *Scripts) ([]byte, error) {
	files := []archiveFile{{name: pkginfoName, data: renderPKGINFO(info, dataHash)}}

	for _, e := range s.entries() {
		if e.body != "" {
			files = append(files, archiveFile{name: e.name, data: []byte(e.body), mode: 0o755})
		}
	}

	return gzipTar(files, false, packageGzip)
}

// renderPKGINFO renders the .PKGINFO text of a package whose fields have been
// validated.
func renderPKGINFO(info *Info, dataHash string) []byte {
	var b bytes.Buffer

	line := func(key, val string) {
		if val != "" {
			b.WriteString(key + " = " + val + "\n")
		}
	}

	number := func(key string, n int64) {
		if n > 0 {
			line(key, strconv.FormatInt(n, 10))
		}
	}

	list := func(key string, vals []string) {
		for _, v := range vals {
			line(key, v)
		}
	}

	if info.Generator != "" {
		b.WriteString("# Generated by " + info.Generator + "\n")
	}

	line("pkgname", info.Name)
	line("pkgver", info.Version)
	line("pkgdesc", info.Description)
	line("url", info.URL)

	if !info.BuildDate.IsZero() {
		number("builddate", info.BuildDate.Unix())
	}

	line("packager", info.Packager)
	number("size", info.InstalledSize)
	line("arch", info.Arch)
	line("origin", info.Origin)
	line("commit", info.Commit)
	line("maintainer", info.Maintainer)
	line("license", info.License)
	list("replaces", info.Replaces)
	list("provides", info.Provides)
	list("depend", info.Depends)
	line("install_if", strings.Join(info.InstallIf, " "))
	number("provider_priority", int64(info.ProviderPriority))
	line("datahash", dataHash)

	return b.Bytes()
}
