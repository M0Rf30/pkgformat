package deb

import (
	"fmt"
	"io"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// Stanza is one package entry of a Packages file read from an index: the
// identifying fields a merge keys on plus the verbatim text.
type Stanza struct {
	Package      string
	Version      string
	Architecture string
	// Filename is the pool-relative path the entry downloads from.
	Filename string
	SHA256   string
	// Text is the stanza as read (comments dropped), ending with a blank line.
	Text string
}

// ScanPackages calls fn for every stanza of a Packages file in order. Field
// names are matched case-insensitively (apt does). A stanza without a Package
// field is skipped; fn returning an error stops the scan with it. Limits
// apply as for ScanControl.
func ScanPackages(r io.Reader, fn func(Stanza) error) error {
	return scanParagraphs(r, func(text string) error {
		cur := Stanza{Text: text + "\n"}

		for line := range strings.SplitSeq(text, "\n") {
			cur.setField(line)
		}

		if cur.Package == "" {
			return nil
		}

		return fn(cur)
	})
}

// setField records line when it is one of the fields a stanza is keyed on.
func (s *Stanza) setField(line string) {
	if line == "" || line[0] == ' ' || line[0] == '\t' {
		return
	}

	name, value, ok := strings.Cut(line, ":")
	if !ok {
		return
	}

	value = strings.TrimSpace(value)

	switch {
	case strings.EqualFold(name, "Package"):
		s.Package = value
	case strings.EqualFold(name, "Version"):
		s.Version = value
	case strings.EqualFold(name, "Architecture"):
		s.Architecture = value
	case strings.EqualFold(name, "Filename"):
		s.Filename = value
	case strings.EqualFold(name, "SHA256"):
		s.SHA256 = value
	}
}

// IndexEntry is a binary package as it is listed in a Packages index.
type IndexEntry struct {
	Name    string
	Version string
	Arch    string
	// InstalledSize is the Installed-Size in KiB; zero omits the field.
	InstalledSize int64
	// Filename is the path of the .deb relative to the repository root, such as
	// PoolPath returns.
	Filename string
	// Size is the size of the .deb in bytes.
	Size int64
	// MD5sum, SHA1, SHA256 and SHA512 are the hex digests of the .deb; empty
	// ones are omitted.
	MD5sum, SHA1, SHA256, SHA512 string
	// Control holds the other control fields of the package (Depends, Section,
	// Description, ...). Fields the repository owns (Package, Version,
	// Architecture, Installed-Size, Filename, Size and the digests) are ignored
	// when present.
	Control map[string]string
}

// EntryFromControl builds the index entry of a package file from its control
// fields and the facts about the file: path in the repository, size and digests.
// Fields of cf the index owns are taken from cf (name, version, architecture,
// installed size) or from the file facts, never copied through.
func EntryFromControl(cf *ControlFile, file FileInfo) (IndexEntry, error) {
	pkg, err := cf.ParsePackage()
	if err != nil {
		return IndexEntry{}, err
	}

	return IndexEntry{
		Name:          pkg.Package,
		Version:       pkg.Version,
		Arch:          pkg.Architecture,
		InstalledSize: pkg.InstalledSize,
		Filename:      file.Path,
		Size:          file.Size,
		MD5sum:        file.MD5sum,
		SHA1:          file.SHA1,
		SHA256:        file.SHA256,
		SHA512:        file.SHA512,
		Control:       ControlFieldsToStore(cf.Fields),
	}, nil
}

// controlFieldOrder is the conventional field order of a Packages stanza.
func controlFieldOrder() []string {
	return []string{
		"Package", "Source", "Version", "Architecture", "Maintainer", "Installed-Size",
		"Pre-Depends", "Depends", "Recommends", "Suggests", "Enhances", "Breaks",
		"Conflicts", "Provides", "Replaces", "Built-Using", "Essential", "Multi-Arch",
		"Section", "Priority", "Homepage",
	}
}

// ownedFields are generated by the repository from the file and must not be
// taken from an uploaded control stanza.
func ownedFields() []string {
	return []string{
		"Package", "Version", "Architecture", "Installed-Size",
		"Filename", "Size", "MD5sum", "SHA1", "SHA256", "SHA512", "Description",
	}
}

// canonicalField maps a control field name onto its canonical spelling when it
// is a field the index knows or owns. apt matches field names
// case-insensitively, so "filename" or "sha256" in an uploaded stanza is the
// same field as "Filename"/"SHA256" and must not slip past the owned-field
// filter. Unknown fields keep their spelling.
func canonicalField(k string) string {
	for _, f := range controlFieldOrder() {
		if strings.EqualFold(k, f) {
			return f
		}
	}

	for _, f := range ownedFields() {
		if strings.EqualFold(k, f) {
			return f
		}
	}

	return k
}

func isOwnedField(k string) bool {
	return slices.Contains(ownedFields(), canonicalField(k))
}

// canonicalFields rewrites every key to its canonical spelling. Spelling
// variants of one field collapse deterministically: the exact canonical key
// wins, otherwise the lexically smallest variant.
func canonicalFields(fields map[string]string) map[string]string {
	keys := make([]string, 0, len(fields))
	for k := range fields {
		keys = append(keys, k)
	}

	sort.Strings(keys)

	out := make(map[string]string, len(fields))

	for _, k := range keys {
		c := canonicalField(k)
		if _, dup := out[c]; dup && k != c {
			continue
		}

		out[c] = fields[k]
	}

	return out
}

// ControlFieldsToStore returns the subset of control fields worth keeping to
// render an index entry later: everything but the fields the repository
// derives from the file (the description is kept).
func ControlFieldsToStore(fields map[string]string) map[string]string {
	canon := canonicalFields(fields)
	out := make(map[string]string, len(canon))

	for k, v := range canon {
		if !isOwnedField(k) || k == "Description" {
			out[k] = v
		}
	}

	return out
}

// FormatPackagesEntry renders a complete Packages stanza, terminated by a
// blank line, for the entry.
func FormatPackagesEntry(e IndexEntry) string {
	var sb strings.Builder

	fields := canonicalFields(e.Control)

	write := func(k, v string) {
		if v == "" {
			return
		}

		writeField(&sb, k, v)
	}

	write("Package", e.Name)

	for _, k := range controlFieldOrder()[1:] {
		switch k {
		case "Version":
			write(k, e.Version)
		case "Architecture":
			write(k, e.Arch)
		case "Installed-Size":
			if e.InstalledSize > 0 {
				write(k, strconv.FormatInt(e.InstalledSize, 10))
			}
		default:
			write(k, fields[k])
		}
	}

	known := controlFieldOrder()
	extra := make([]string, 0)

	for k := range fields {
		if !slices.Contains(known, k) && !isOwnedField(k) {
			extra = append(extra, k)
		}
	}

	sort.Strings(extra)

	for _, k := range extra {
		write(k, fields[k])
	}

	write("Filename", e.Filename)
	write("Size", strconv.FormatInt(e.Size, 10))
	write("MD5sum", e.MD5sum)
	write("SHA1", e.SHA1)
	write("SHA256", e.SHA256)
	write("SHA512", e.SHA512)
	write("Description", fields["Description"])
	sb.WriteString("\n")

	return sb.String()
}

// Index accumulates the entries of a Packages index and renders it plain or
// compressed. The zero value is an empty index.
type Index struct {
	entries []string
	// rendered caches Bytes; Add and AddText invalidate it so the plain and
	// compressed variants share one render.
	rendered []byte
}

// Add appends the stanza of e.
func (ix *Index) Add(e IndexEntry) { ix.AddText(FormatPackagesEntry(e)) }

// AddText appends a stanza as is, such as Stanza.Text. A stanza without a
// final blank line gets one.
func (ix *Index) AddText(stanza string) {
	if stanza == "" {
		return
	}

	if !strings.HasSuffix(stanza, "\n\n") {
		stanza = strings.TrimRight(stanza, "\n") + "\n\n"
	}

	ix.entries = append(ix.entries, stanza)
	ix.rendered = nil
}

// Len is the number of stanzas.
func (ix *Index) Len() int { return len(ix.entries) }

// Bytes renders the index. The result is shared; do not modify it.
func (ix *Index) Bytes() []byte {
	if ix.rendered != nil {
		return ix.rendered
	}

	n := 0
	for _, e := range ix.entries {
		n += len(e)
	}

	b := make([]byte, 0, n)
	for _, e := range ix.entries {
		b = append(b, e...)
	}

	ix.rendered = b

	return b
}

// Compressed renders the index compressed with c.
func (ix *Index) Compressed(c Compression) ([]byte, error) {
	var buf sliceWriter

	if _, err := ix.WriteTo(&buf, c); err != nil {
		return nil, err
	}

	return buf.b, nil
}

// WriteTo writes the index compressed with c to w and returns the number of
// bytes written to w.
func (ix *Index) WriteTo(w io.Writer, c Compression) (int64, error) {
	cw := &countingWriter{w: w}

	zw, err := compressWriter(cw, c)
	if err != nil {
		return 0, err
	}

	if _, err := zw.Write(ix.Bytes()); err != nil {
		_ = zw.Close()

		return cw.n, fmt.Errorf("deb: writing index: %w", err)
	}

	if err := zw.Close(); err != nil {
		return cw.n, fmt.Errorf("deb: closing index: %w", err)
	}

	return cw.n, nil
}

type sliceWriter struct{ b []byte }

func (s *sliceWriter) Write(p []byte) (int, error) {
	s.b = append(s.b, p...)

	return len(p), nil
}

// countingWriter counts the bytes written through it.
type countingWriter struct {
	w io.Writer
	n int64
}

func (cw *countingWriter) Write(p []byte) (int, error) {
	n, err := cw.w.Write(p)
	cw.n += int64(n)

	return n, err
}
